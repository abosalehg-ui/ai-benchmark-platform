"""خلط خيارات الاختيار من متعدّد خلطاً حتمياً.

**المشكلة التي تحلّها هذه الوحدة:** فحص ملفات الداتاست أظهر أن موضع الإجابة
الصحيحة لم يكن موزّعاً: 130 من 150 إجابة في ``saudi_legal.json`` على الحرف «ب»
(86.7%)، و95% منها كان **الخيار الأطول**. عملياً كان نموذج يجيب «ب» دائماً بلا
قراءة السؤال يحصل على 86.7%، ونموذج يختار أطول خيار يحصل على 94.7% — أي أن
الفرق بين نموذج ممتاز ونموذج يخمّن بالطول كان خمس نقاط مئوية، وهو **أقل** من
هامش فاصل ويلسون عند 150 سؤالاً (‎±5.4‎). البنشمارك لم يكن يفرّق بين النماذج،
وصفحة «الانحراف عبر الزمن» المبنية فوقه كانت ترصد ضجيجاً لا انحرافاً.

الانحياز كان في كل تصنيف من الثلاثة عشر («نظام الإثبات» و«نظام الشركات»:
12/12 على «ب»)، فلم يكن مشكلة دفعة واحدة من الأسئلة يمكن إصلاحها بتحرير الملف.

**لماذا الخلط حتمي لا عشوائي:** ترتيب الخيارات جزء من نصّ الـ prompt، فهو جزء
من مفتاح الـ cache ومن معنى «نفس التشغيل». خلط عشوائي عند كل تحميل يجعل
تشغيلين على نفس البنشمارك غير قابلين للمقارنة — وهو بالضبط ما تحتاجه صفحة
الانحراف وما يحتاجه الـ cache. البذرة مشتقّة من (اسم البنشمارك + معرّف المسألة)،
و``random.seed`` مع سلسلة نصّية يمرّ عبر SHA-512 منذ بايثون 3.2، فالترتيب ثابت
عبر التشغيلات والأجهزة وإصدارات بايثون، ومختلف بين مسألة وأخرى وبين بنشمارك
وآخر.

**أثر جانبي مقصود ومعلوم:** الـ prompt تغيّر، فمدخلات الـ cache المحفوظة قبل
هذا التغيير لن تُصاب (مفتاحها يشمل الـ prompt) وستُعاد الاستدعاءات مرّة واحدة.
وتشغيلات ما قبل التغيير في صفحة الانحراف تقارَن بتشغيلات ما بعده على نفس
البنشمارك: الفرق بينها قد يعكس تصحيح التحيّز لا تغيّر النموذج. هذا مذكور في
README قسم «تتبّع الانحراف عبر الزمن».
"""
from __future__ import annotations

import random


def shuffle_choices(
    choices: list[str],
    answer: str,
    letters: str,
    seed: str,
) -> tuple[list[str], str]:
    """يخلط الخيارات ويرجع ``(الخيارات بعد الخلط، حرف الإجابة الجديد)``.

    ``letters`` أبجدية البنشمارك (``أبجد`` أو ``ABCD``)، و``seed`` بذرة نصّية
    ثابتة لكل مسألة. البيانات التالفة تمرّ كما هي بلا خلط وبلا استثناء: مسألة
    واحدة بحرف إجابة غير معروف لا تُسقط تحميل الداتاست كلّه.
    """
    if not choices or not isinstance(answer, str) or answer not in letters:
        return list(choices), answer

    answer_index = letters.index(answer)
    if answer_index >= len(choices):
        # حرف إجابة يشير إلى خيار غير موجود — بيانات تالفة، نتركها للتقييم
        # ليرصدها بدل أن نخفيها خلف خلط يعطيها معنىً جديداً
        return list(choices), answer

    order = list(range(len(choices)))
    random.Random(seed).shuffle(order)
    shuffled = [choices[i] for i in order]
    # ``order[j] == i`` يعني أن الموضع الجديد j يحمل الخيار القديم i،
    # فموضع الإجابة الجديد هو موقع ``answer_index`` داخل ``order``
    return shuffled, letters[order.index(answer_index)]
